def sha(value: object) -> str:
    raw = json.dumps(value, ensure_ascii=False, sort_keys=True, separators=(",", ":")).encode("utf-8")
    return hashlib.sha256(raw).hexdigest()


def extract_rubrics(path: Path) -> tuple[dict, dict]:
    """Read the literal SCORE_CRITERIA call keywords without importing the seed."""
    raw = path.read_bytes()
    tree = ast.parse(raw.decode("utf-8-sig"))
    found = None
    for node in tree.body:
        if isinstance(node, (ast.Assign, ast.AnnAssign)):
            targets = node.targets if isinstance(node, ast.Assign) else [node.target]
            if any(isinstance(target, ast.Name) and target.id == "SCORE_CRITERIA" for target in targets):
                found = node.value
    rubrics = {}
    if isinstance(found, (ast.Tuple, ast.List)):
        for item in found.elts:
            if not isinstance(item, ast.Call) or not isinstance(item.func, ast.Name) or item.func.id != "ScoreCriterionSpec":
                raise ValueError("rubric_inventory_invalid")
            values = {keyword.arg: ast.literal_eval(keyword.value) for keyword in item.keywords}
            key = values["score_key"]
            if key in rubrics:
                raise ValueError("rubric_inventory_invalid")
            rubrics[key] = values["rubric"]
    if set(rubrics) != set(KEYS) or any(set(rows) != set("01234") or any(type(text) is not str or not text.strip() for text in rows.values()) for rows in rubrics.values()):
        raise ValueError("rubric_inventory_invalid")
    return rubrics, {"source_path": "backend/scripts/seed_score_criteria.py", "source_sha256": hashlib.sha256(raw).hexdigest(), "rubrics_sha256": sha(rubrics), "method": "ast.literal_eval_only_no_seed_import", "review_status": "unreviewed"}


