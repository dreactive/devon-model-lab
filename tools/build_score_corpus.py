def _validate_service(envelope: dict, devon_root: Path):
    attach_devon(devon_root)
    from devon_ai import contracts as c
    from devon_ai.llm_tasks import report as original_report, report_score
    try:
        turns, rubric, report_input = original_report._build_inputs(envelope["payload"]["service_input"])
        report_score.check_input(turns, rubric)
        c.validate_report_input(report_input)
        c.validate_supplemental_input(report_input.supplemental_sources, contracts=tuple(turn.question_contract for turn in turns), limitations=report_input.limitations)
    except (c.ContractError, TypeError, ValueError, KeyError) as exc:
        raise ValueError("original_input_invalid") from exc
    return turns, rubric, report_input


def _write_new(path: Path, value: object):
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("x", encoding="utf-8", newline="\n") as stream:
        json.dump(value, stream, ensure_ascii=False, indent=2, allow_nan=False)
        stream.write("\n")


